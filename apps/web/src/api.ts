/**
 * Small API client for the web app.
 *
 * In production nginx proxies `/api` to the backend; in development Vite's
 * proxy does the same. Therefore the default base URL is empty (relative),
 * which also avoids CORS problems. `VITE_API_BASE_URL` exists only for special
 * deployments where the API lives on another host.
 */

/** Shape returned by `GET /api/health` (mirrors backend/app/api/health.py). */
export interface HealthResponse {
  status: string;
  version: string;
}

/**
 * Fetch the backend health status.
 *
 * @param signal optional AbortSignal so a component can cancel on unmount
 * @returns parsed health response
 * @throws Error when the network fails or the backend answers non-2xx
 */
export async function fetchHealth(signal?: AbortSignal): Promise<HealthResponse> {
  const baseUrl = import.meta.env.VITE_API_BASE_URL ?? "";
  const response = await fetch(`${baseUrl}/api/health`, { signal });

  if (!response.ok) {
    throw new Error(`Backend returned HTTP ${response.status}`);
  }

  // The response is generated by FastAPI, so we trust the documented shape.
  return (await response.json()) as HealthResponse;
}
